    ON historial_estados_plaza(plaza_id, cambiado_en DESC);

CREATE INDEX IF NOT EXISTS indice_historial_plaza_usuario
    ON historial_estados_plaza(cambiado_por_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_plaza
    ON requisitos_plaza(plaza_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_tipo
    ON requisitos_plaza(codigo_tipo);

CREATE INDEX IF NOT EXISTS indice_requisitos_habilidad
    ON requisitos_habilidad(habilidad_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_idioma
    ON requisitos_idioma(idioma_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_certificacion
    ON requisitos_certificacion(certificacion_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_educacion_nivel
    ON requisitos_educacion(nivel_educativo_minimo_id);

CREATE INDEX IF NOT EXISTS indice_requisitos_experiencia_profesion
    ON requisitos_experiencia(profesion_id);

