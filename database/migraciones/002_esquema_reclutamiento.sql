    ON analisis_cv(curriculo_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS indice_analisis_motor
    ON analisis_cv(motor_analisis_id);

CREATE UNIQUE INDEX IF NOT EXISTS indice_analisis_vigente_curriculo
    ON analisis_cv(curriculo_id)
    WHERE vigente;

CREATE INDEX IF NOT EXISTS indice_experiencias_analisis
    ON experiencias_analisis_cv(analisis_id);

CREATE INDEX IF NOT EXISTS indice_experiencias_profesion
    ON experiencias_analisis_cv(profesion_id);

CREATE INDEX IF NOT EXISTS indice_educaciones_analisis
    ON educaciones_analisis_cv(analisis_id);

CREATE INDEX IF NOT EXISTS indice_habilidades_analisis
    ON habilidades_analisis_cv(analisis_id);

CREATE INDEX IF NOT EXISTS indice_habilidades_catalogo_analisis
    ON habilidades_analisis_cv(habilidad_id)
    WHERE habilidad_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS indice_idiomas_analisis
    ON idiomas_analisis_cv(analisis_id);

CREATE INDEX IF NOT EXISTS indice_certificaciones_analisis
    ON certificaciones_analisis_cv(analisis_id);

CREATE INDEX IF NOT EXISTS indice_evaluaciones_postulacion_fecha
    ON evaluaciones_postulacion(postulacion_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS indice_evaluaciones_analisis
    ON evaluaciones_postulacion(analisis_cv_id);

CREATE UNIQUE INDEX IF NOT EXISTS indice_evaluacion_vigente_postulacion
    ON evaluaciones_postulacion(postulacion_id)
    WHERE vigente;

CREATE INDEX IF NOT EXISTS indice_evaluacion_compatibilidad_vigente
    ON evaluaciones_postulacion(porcentaje_compatibilidad DESC)
    WHERE vigente AND codigo_estado = 'COMPLETADO';

CREATE INDEX IF NOT EXISTS indice_resultados_requisito
    ON resultados_requisitos_evaluacion(requisito_id);
