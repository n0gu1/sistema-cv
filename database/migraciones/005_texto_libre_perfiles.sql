UPDATE perfiles_aspirantes AS perfil
SET profesion_texto = profesion.nombre
FROM profesiones AS profesion
WHERE perfil.profesion_id = profesion.id
  AND NULLIF(BTRIM(perfil.profesion_texto), '') IS NULL;

UPDATE perfiles_aspirantes AS perfil
SET ciudad_texto = ciudad.nombre
FROM ciudades AS ciudad
WHERE perfil.ciudad_id = ciudad.id
  AND NULLIF(BTRIM(perfil.ciudad_texto), '') IS NULL;

