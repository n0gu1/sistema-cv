UPDATE certificaciones_aspirantes AS certificacion_aspirante
SET certificacion_texto = certificacion.nombre,
    organizacion_emisora_texto = certificacion.organizacion_emisora
FROM certificaciones AS certificacion
WHERE certificacion_aspirante.certificacion_id = certificacion.id
  AND (
      NULLIF(BTRIM(certificacion_aspirante.certificacion_texto), '') IS NULL
      OR NULLIF(BTRIM(certificacion_aspirante.organizacion_emisora_texto), '') IS NULL
  );

